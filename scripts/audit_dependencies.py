#!/usr/bin/env python3
"""Security audit of every library the packages ship (D-67).

Four checks, each usable alone, and the software bill of materials:

--vulnerabilities  Every shipped library is resolved to the exact commit it is built from (the
                   overlay port's pinned commit, or the release tag of the version the vcpkg
                   baseline or packaging/qt-version.txt pins) and that commit is looked up in OSV
                   (https://osv.dev: OSS-Fuzz, the CVE list and GitHub's advisories, by commit). A
                   vulnerability fixed in a release we may take is "actionable": the update must
                   happen now, whatever the cooldown (D-67). Every other one must be answered (D-73):
                   by a patch of ours ("Fixes:" in an imageviewer-*.patch of its overlay port) or by a
                   person's assessment in packaging/known-vulnerabilities.txt; one that is neither is
                   "unassessed". A library whose commit cannot be resolved fails.

--sources          The libraries built from a release tarball rather than from a commit of their
                   repository (where the xz backdoor of 2024 hid: in the tarball, not in git) are
                   compared, file by file, with the repository at the release's tag. A file that
                   differs, or exists only in the tarball, fails the check unless it is listed as
                   generated by the release process and regenerated by our build.

--cooldown         Fails when a shipped release (or vcpkg's port recipes at the baseline) is younger
                   than the cooldown and has no recorded exception (packaging/cooldown-exceptions.txt):
                   a compromised release is usually found and withdrawn within days. The release
                   workflow runs it before publishing. The cooldown, in days, is the number in
                   packaging/cooldown-days.txt (15, the policy; the owner may lower it for a
                   release, and a lowered one is reported: the flag "lowered").

--coverage DIR     Fails when a library installed in DIR (vcpkg's installed tree, "share/<port>")
                   is missing from this audit's list: nothing ships unaudited.

The SVG renderer (D-90) is audited as three things: resvg, by the commit its overlay port pins, as
the other libraries; every crate of the port's Cargo.lock, in OSV by its name and version and
through the cooldown by its publication date on crates.io (the lock pins each crate's checksum,
which cargo verifies, so no archive is compared); and the Rust toolchain whose standard library is
compiled in, by the commit of its release tag and the tag's date. A crate's known vulnerability is
answered as any other: by an assessment in packaging/known-vulnerabilities.txt, as "crate/<name>".

Exit status: 0 clean; 1 an actionable or unassessed vulnerability, a source that does not match its
tag, a release under the cooldown, or an unaudited library; 2 a check could not run (network, or an
unreadable file of packaging/: cooldown-days.txt, cooldown-exceptions.txt, known-vulnerabilities.txt).
The report (Markdown) goes to stdout and, with --report, to a file; with $GITHUB_OUTPUT set, the
flags "vulnerable", "actionable", "unassessed", "mismatch", "young", "unaudited", "failed" and
"lowered" too, and "cooldown_days".

--sbom DIR FILE VERSION  Writes the SPDX 2.3 document (software bill of materials) of a package
                   built from DIR: ImageViewer, every library from vcpkg with its upstream source
                   and checksum, and Qt's modules. A release attests it with the package.

usage: python3 scripts/audit_dependencies.py [--vulnerabilities] [--sources] [--cooldown] [--coverage DIR]
                                            [--report FILE]
       python3 scripts/audit_dependencies.py --sbom DIR FILE VERSION
"""
