def our_patches(port):
    """The patches we carry in an overlay port (imageviewer-*.patch, D-57, D-73), each a dict of its
    header's fields: "file", "fixes" (the vulnerability ids of its "Fixes:" line), "upstream" and
    "remove" (its "Upstream:" and "Remove when:" lines). The header is the text before the diff,
    which git apply skips; docs/PLAN.md section 15 lists the same patches for people."""
    directory = os.path.join(PORTS, port)
    patches = []
    for name in sorted(os.listdir(directory)) if os.path.isdir(directory) else []:
        if not (name.startswith("imageviewer-") and name.endswith(".patch")):
            continue
        header = read(os.path.join(directory, name)).split("\ndiff --git ", 1)[0]
        fields = dict(re.findall(r"^(Library|Fixes|Upstream|Remove when): (.+)$", header, re.M))
        if not {"Library", "Fixes", "Upstream", "Remove when"} <= set(fields):
            raise ValueError(f"{port}/{name}: its header needs Library:, Fixes:, Upstream: and Remove when: lines")
        patches.append(dict(file=name, fixes=set(VULNERABILITY_ID.findall(fields["Fixes"])),
                            upstream=fields["Upstream"], remove=fields["Remove when"]))
    return patches


def crates():
    """[(name, version, checksum)] of every crate from crates.io in the SVG renderer's Cargo.lock (D-90),
    which builds resvg with `cargo build --locked`."""
    import tomllib  # Python 3.11
    with open(os.path.join(SVG_PORT, "Cargo.lock"), "rb") as f:
        lock = tomllib.load(f)
    return [(p["name"], p["version"], p.get("checksum")) for p in lock["package"]
            if p.get("source", "").startswith("registry+")]


def rust_version():
    """The Rust release that builds the SVG renderer (its rust-toolchain.toml, D-90)."""
    match = re.search(r'^channel = "(\d+\.\d+\.\d+)"$', read(os.path.join(SVG_PORT, "rust-toolchain.toml")), re.M)
    if not match:
        raise ValueError("packaging/vcpkg/ports/imageviewer-svg/rust-toolchain.toml: no Rust release pinned")
    return match.group(1)


def crate_date(name, version):
    """When crates.io published a crate's version (set by crates.io, not by the publisher). crates.io
    allows one request a second."""
    import time
    time.sleep(1)
    data = json.loads(fetch(f"{CRATES_IO}/{urllib.parse.quote(name)}/{urllib.parse.quote(version)}"))
    return datetime.datetime.fromisoformat(data["version"]["created_at"].replace("Z", "+00:00"))


def release_tags(url, templates, name=""):
    """{version tuple: (tag, commit)} of every release tag matching the "|"-separated templates."""
    patterns = [re.escape(t).replace(r"\{v\}", r"(\d+(?:\.\d+)*)").replace(r"\{v_\}", r"(\d+(?:_\d+)*)")
                for t in templates.split("|")]
    tags = {}
    for line in run("git", "ls-remote", "--tags", url).splitlines():
        commit, ref = line.split("\t")
        tag = ref.removeprefix("refs/tags/").removesuffix("^{}")
        for pattern in patterns:
            if match := re.fullmatch(pattern, tag):
                version = tuple(int(p) for p in re.split(r"[._]", match.group(1)))
                if not (name in PRERELEASE and PRERELEASE[name](version)):
                    tags[version] = (tag, commit)  # an annotated tag's peeled line comes last
                break
    return tags


def shipped(baseline):
    """Every shipped library: {name, version, url, commit or None, how, templates, keep}, where
    `keep` is how many leading version parts an update keeps (1: the major version; Qt: 2)."""
    libraries = []
    for port, (url, template) in COMMIT_PORTS.items():
        commit, tag = re.search(r"REF ([0-9a-f]{40}) # (\S+)", read(os.path.join(PORTS, port, "portfile.cmake"))).groups()
        libraries.append(dict(name=port, version=overlay_version(port), url=url, commit=commit, how=f"overlay, {tag}",
                              templates=template, keep=1))
    for port, (kind, url, template) in TARBALL_PORTS.items():
        version = overlay_version(port)
        commit = release_tag(url, template, version)[1] if kind == "git" else None
        libraries.append(dict(name=port, version=version, url=url, commit=commit, how="overlay, release tarball",
                              templates=template if kind == "git" else None, keep=1))
    for port, (url, template) in BASELINE_PORTS.items():
        version = baseline.get(port)
        if version is None:
            raise RuntimeError(f"{port} is not in the vcpkg baseline")
        libraries.append(dict(name=port, version=version, url=url, commit=release_tag(url, template, version)[1],
                              how="vcpkg baseline", templates=template, keep=1))
    qt = read(os.path.join(ROOT, "packaging", "qt-version.txt")).strip()
    for module in QT_MODULES:
        url = f"https://github.com/qt/{module}"
        libraries.append(dict(name=module, version=qt, url=url, commit=release_tag(url, "v{v}", qt)[1],
                              how="Qt (official binaries)", templates="v{v}", keep=2))
    rust = rust_version()  # its standard library is compiled into the SVG renderer (D-90)
    libraries.append(dict(name="rust", version=rust, url=RUST, commit=release_tag(RUST, "{v}", rust)[1],
                          how="Rust toolchain (the SVG renderer)", templates="{v}", keep=1))
    return libraries


def ripening(lib):
    """The day the library's newest allowed release (lib["newest"]) passes the cooldown, or None when
    it is past it, excepted, or cannot be dated (never a reason to wait)."""
    version, _, tag = lib["newest"]
    if f"{lib['name']} {version}" in COOLDOWN_EXCEPTIONS:
        return None
    try:
        when = tag_date(lib["url"], tag)[0]
    except Exception:
        return None
    if age_days(when) >= MIN_RELEASE_AGE_DAYS:
        return None
    return (when + datetime.timedelta(days=MIN_RELEASE_AGE_DAYS)).date().isoformat()


def osv_lookup(commits):
    """{commit: [(id, CVE aliases, summary, fixed upstream)]} from OSV; withdrawn entries left out."""
    commits = list(dict.fromkeys(commits))
    return dict(zip(commits, osv_query([{"commit": c} for c in commits])))


def osv_crates(pinned):
    """{(name, version): [(id, aliases, summary, fixed upstream)]} of crates from crates.io, from OSV."""
    return dict(zip(pinned, osv_query([{"package": {"ecosystem": "crates.io", "name": n}, "version": v}
                                       for n, v in pinned])))


def osv_query(queries):
    """[[(id, CVE aliases, summary, fixed upstream)] per query] from OSV's batch query; withdrawn
    entries left out."""
    if not queries:
        return []
    results = json.loads(fetch(f"{OSV}/querybatch", json.dumps({"queries": queries}).encode()))["results"]
    details, found = {}, []
    for query, result in zip(queries, results):
        if result.get("next_page_token"):
            raise RuntimeError(f"OSV paginated the results of {query}: query it alone")
        found.append([])
        for vid in (v["id"] for v in result.get("vulns", [])):
            if vid not in details:
                details[vid] = json.loads(fetch(f"{OSV}/vulns/{vid}"))
            entry = details[vid]
            if entry.get("withdrawn"):
                continue
            fixed = any("fixed" in e for a in entry.get("affected", []) for r in a.get("ranges", [])
                        for e in r.get("events", []))
            aliases = ", ".join(a for a in entry.get("aliases", []) if a.startswith(("CVE-", "RUSTSEC-", "GHSA-")))
            summary = (entry.get("summary") or entry.get("details", "").split("\n")[0])[:120]
            found[-1].append((vid, aliases, summary, fixed))
    return found


def vulnerabilities(libraries, report):
    """OSV, by commit: the pinned release, and the newest release the update policy allows. A known
    vulnerability is "actionable" when that newest release is free of it: the update must happen
    now (D-67), with a cooldown exception if the release is younger than the cooldown. Not when the
    vulnerability is assessed out of our reach and that release is still under the cooldown: D-69
    asks for an exception only for an issue we can reach, so it is taken once past the cooldown,
    and is actionable from that day (D-92). Any other one is answered by a patch of ours ("Fixes:",
    D-73) or by an assessment in packaging/known-vulnerabilities.txt, or else is "unassessed": a
    person must look at it before a release ships. Returns (vulnerable, actionable, unassessed,
    unresolved), where "vulnerable" means a known vulnerability that no patch of ours fixes."""
    unresolved = unassessed = False
    reported = set()
    for lib in libraries:
        lib["newest"] = None
        if not lib["commit"]:
            continue
        current = tuple(int(p) for p in re.split(r"[._]", lib["version"]))
        try:
            tags = release_tags(lib["url"], lib["templates"], lib["name"])
        except subprocess.CalledProcessError:
            tags = {}
        allowed = [v for v in tags if v[:lib["keep"]] == current[:lib["keep"]] and v > current]
        if allowed:
            lib["newest"] = (".".join(map(str, max(allowed))), tags[max(allowed)][1], tags[max(allowed)][0])
    found = osv_lookup([lib["commit"] for lib in libraries if lib["commit"]] +
                       [lib["newest"][1] for lib in libraries if lib["newest"]])
    vulnerable = actionable = False
    for lib in libraries:
        name, version, url, commit, how = lib["name"], lib["version"], lib["url"], lib["commit"], lib["how"]
        patched = {vid: patch["file"] for patch in our_patches(name) for vid in patch["fixes"]}
        if not commit:
            if name in TARBALL_PORTS and TARBALL_PORTS[name][0] == "hg":
                report.notes.append(f"{name} {version}: its repository is Mercurial, which OSV does not index by "
                                    f"commit; read its NEWS for security fixes at every update ({url}).")
                report.rows.append(f"| {name} | {version} | — | {how} | not in OSV's commit index (see below) |")
                continue
            unresolved = True
            report.notes.append(f"**{name} {version}: its release tag could not be resolved to a commit** ({url}): "
                                f"the tag's name changed, or the host was unreachable. Fix the entry in "
                                f"scripts/audit_dependencies.py; until then this library is not audited.")
            report.rows.append(f"| {name} | {version} | — | {how} | **not resolved** |")
            continue
        entries = found.get(commit, [])
        ids = {vid for vid, _, _, _ in entries} | {a.strip() for _, aliases, _, _ in entries for a in aliases.split(",") if a.strip()}
        for vid in sorted(set(patched) - ids):
            report.notes.append(f"{name} {version}: `{patched[vid]}` fixes {vid}, which OSV no longer reports for "
                                f"`{commit[:10]}`: check whether the patch is still needed (D-57).")
        if not entries:
            report.rows.append(f"| {name} | {version} | `{commit[:10]}` | {how} | none known |")
            continue
        newer = {vid for vid, _, _, _ in found.get(lib["newest"][1], [])} if lib["newest"] else None
        listed = []
        for vid, aliases, summary, fixed in entries:
            names = {vid, *(a.strip() for a in aliases.split(",") if a.strip())}
            reported |= {(name, n) for n in names}
            patch = next((patched[n] for n in names if n in patched), None)
            known = next((KNOWN_VULNERABILITIES[(name, n)] for n in names if (name, n) in KNOWN_VULNERABILITIES), None)
            if patch:
                state = f"patched: `{patch}`" + (f" (also fixed in {lib['newest'][0]}: the update takes it and drops "
                                                 f"the patch)" if newer is not None and vid not in newer else "")
            elif newer is not None and vid not in newer and known and (ripens := ripening(lib)):
                vulnerable = True
                state = (f"assessed: {known}; fixed in {lib['newest'][0]}, under the cooldown until {ripens}: "
                         f"taken then, and \"update now\" from that day (D-69, D-92)")
            elif newer is not None and vid not in newer:
                vulnerable = actionable = True
                state = f"**fixed in {lib['newest'][0]}: update now**"
            elif known:
                vulnerable = True
                state = f"assessed: {known}"
            else:
                vulnerable = unassessed = True
                state = ("**not assessed**: " + ("fixed upstream, in no release the update policy allows yet" if fixed
                                                 else "no fix recorded") +
                         "; answer it with a patch (docs/PLAN.md section 15) or a line in packaging/known-vulnerabilities.txt")
            report.notes.append(f"**{name} {version}: {vid}**{f' ({aliases})' if aliases else ''}: {summary} — "
                                f"{state}. https://osv.dev/vulnerability/{vid}")
            listed.append(vid + (f" ({aliases})" if aliases else "") + (" patched" if patch else ""))
        report.rows.append(f"| {name} | {version} | `{commit[:10]}` | {how} | **{', '.join(listed)}** |")
    # The SVG renderer's crates (D-90), by name and version: answered only by an assessment, since the
    # lock follows resvg's release (an update of resvg, or of one crate in the lock, takes a fix).
    pinned = [(n, v) for n, v, _ in crates()]
    listed = []
    for (name, version), entries in osv_crates(pinned).items():
        library = f"crate/{name}"
        for vid, aliases, summary, fixed in entries:
            names = {vid, *(a.strip() for a in aliases.split(",") if a.strip())}
            reported |= {(library, n) for n in names}
            known = next((KNOWN_VULNERABILITIES[(library, n)] for n in names if (library, n) in KNOWN_VULNERABILITIES), None)
            vulnerable = True
            if known:
                state = f"assessed: {known}"
            else:
                unassessed = True
                state = ("**not assessed**: " + ("fixed upstream: update resvg, or the crate in the lock "
                                                 "(scripts/update_dependencies.py)" if fixed else "no fix recorded")
                         + f"; answer it with a line '{vid} {library}: ...' in packaging/known-vulnerabilities.txt")
            report.notes.append(f"**{name} {version} (crate of the SVG renderer): {vid}**"
                                f"{f' ({aliases})' if aliases else ''}: {summary} — {state}. https://osv.dev/vulnerability/{vid}")
            listed.append(f"{name} {version}: {vid}")
    report.rows.append(f"| {len(pinned)} crates of imageviewer-svg | Cargo.lock | — | crates.io, checksums in the lock | "
                       + (f"**{', '.join(listed)}** |" if listed else "none known |"))
    if not unresolved:  # with a library unresolved, a line may only look stale
        for library, vid in sorted(set(KNOWN_VULNERABILITIES) - reported):
            report.notes.append(f"`{vid} {library}` is no longer reported for the pinned {library}: remove its line "
                                f"from packaging/known-vulnerabilities.txt.")
    return vulnerable, actionable, unassessed, unresolved


def release_dates(baseline_commit, baseline):
    """[(name, version, (date, how known) or the error)] for every shipped library, and for vcpkg's
    port recipes (they run in our build) at the baseline commit."""
    entries = []

    def add(name, version, date):
        try:
            entries.append((name, version, date()))
        except Exception as error:  # reported per library: one unreachable host hides nothing else
            entries.append((name, version, error))
    for port, (url, _) in COMMIT_PORTS.items():
        tag = re.search(r"REF [0-9a-f]{40} # (\S+)", read(os.path.join(PORTS, port, "portfile.cmake"))).group(1)
        add(port, overlay_version(port), lambda url=url, tag=tag: tag_date(url, tag))
    version = overlay_version("graphicsmagick")
    add("graphicsmagick", version, lambda: (gm_releases()[version], "archive upload date"))
    for port, (url, templates) in BASELINE_PORTS.items():
        version = baseline[port]
        add(port, version, lambda url=url, templates=templates, version=version:
            tag_date(url, release_tag(url, templates, version)[0]))
    add("vcpkg port recipes", baseline_commit[:10], lambda: (ref_date(VCPKG, baseline_commit), "commit date"))
    qt = read(os.path.join(ROOT, "packaging", "qt-version.txt")).strip()
    add("Qt", qt, lambda: tag_date("https://github.com/qt/qtbase", f"v{qt}"))
    rust = rust_version()
    add("rust", rust, lambda: tag_date(RUST, rust))
    return entries


def cooldown(baseline_commit, baseline, report):
    """True when every shipped release is MIN_RELEASE_AGE_DAYS old or has a recorded exception;
    raises when a release cannot be dated (never a pass)."""
    ok, undated = True, []
    names = set()
    for name, version, dated in release_dates(baseline_commit, baseline):
        names.add(f"{name} {version}")
        if isinstance(dated, Exception):
            undated.append(name)
            report.rows.append(f"| {name} | {version} | ? | ? | **could not be dated**: {str(dated)[:100]} |")
            continue
        when, how = dated
        age = age_days(when)
        if age >= MIN_RELEASE_AGE_DAYS:
            status = "ok"
            if f"{name} {version}" in COOLDOWN_EXCEPTIONS:
                report.stale.append(f"{name} {version}")
                report.notes.append(f"`{name} {version}` is past the cooldown: its exception has expired, and "
                                    f"scripts/update_dependencies.py removes it from packaging/cooldown-exceptions.txt.")
        elif f"{name} {version}" in COOLDOWN_EXCEPTIONS:
            status = f"exception: {COOLDOWN_EXCEPTIONS[f'{name} {version}']}"
        else:
            ok = False
            until = (when + datetime.timedelta(days=MIN_RELEASE_AGE_DAYS)).date().isoformat()
            status = f"**under the cooldown until {until}**"
        report.rows.append(f"| {name} | {version} | {when.date().isoformat()} ({how}) | {age:.0f} days | {status} |")
    # The SVG renderer's crates (D-90): each published on crates.io at least the cooldown ago, or
    # excepted as "crate/<name> <version>". One row for all of them, and one for each that is not.
    newest = None
    for name, version, _ in crates():
        key = f"crate/{name} {version}"
        names.add(key)
        try:
            when = crate_date(name, version)
        except Exception as error:
            undated.append(key)
            report.rows.append(f"| {key} | {version} | ? | ? | **could not be dated**: {str(error)[:100]} |")
            continue
        newest = max(newest or (when, key), (when, key))
        if age_days(when) >= MIN_RELEASE_AGE_DAYS:
            if key in COOLDOWN_EXCEPTIONS:  # as for the libraries above: none outlives its release
                report.stale.append(key)
                report.notes.append(f"`{key}` is past the cooldown: its exception has expired, and "
                                    f"scripts/update_dependencies.py removes it from packaging/cooldown-exceptions.txt.")
            continue
        if key in COOLDOWN_EXCEPTIONS:
            status = f"exception: {COOLDOWN_EXCEPTIONS[key]}"
        else:
            ok = False
            status = f"**under the cooldown until {(when + datetime.timedelta(days=MIN_RELEASE_AGE_DAYS)).date().isoformat()}**"
        report.rows.append(f"| {key} | {version} | {when.date().isoformat()} (crates.io) | {age_days(when):.0f} days | {status} |")
    if newest:
        report.rows.append(f"| {len(crates())} crates of imageviewer-svg | Cargo.lock | newest: {newest[1]}, "
                           f"{newest[0].date().isoformat()} (crates.io) | {age_days(newest[0]):.0f} days | "
                           + ("ok" if age_days(newest[0]) >= MIN_RELEASE_AGE_DAYS else "see the rows above") + " |")
    for stale in sorted(set(COOLDOWN_EXCEPTIONS) - names):
        report.stale.append(stale)
        report.notes.append(f"`{stale}` is no longer pinned: scripts/update_dependencies.py removes its exception "
                            f"from packaging/cooldown-exceptions.txt.")
    if MIN_RELEASE_AGE_DAYS < POLICY_DAYS:
        report.notes.append(f"**The cooldown is lowered to {MIN_RELEASE_AGE_DAYS} days** (packaging/cooldown-days.txt; "
                            f"the policy is {POLICY_DAYS}, D-67): set it back to {POLICY_DAYS} once the release that "
                            f"needed it is out.")
    if not ok:
        report.notes.append(f"A release ships only once every library in it is {MIN_RELEASE_AGE_DAYS} days old "
                            f"(D-67): wait for the dates above, or pin an older release, or, for a security "
                            f"fix that cannot wait, record an exception in packaging/cooldown-exceptions.txt after reading "
                            f"the release's changes.")
    if undated:
        raise RuntimeError(f"no release date for {', '.join(undated)} (see the cooldown table)")
    return ok


def sha512_of(path):
    digest = hashlib.sha512()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def tarball_source(port, version, baseline_commit):
    """(archive URL, SHA-512 pinned) of a library built from a release tarball."""
    if port in TARBALL_PORTS:
        text = read(os.path.join(PORTS, port, "portfile.cmake"))
        url = re.search(r'URLS "([^"]+)"', text).group(1).replace("${VERSION}", version)
    else:  # giflib: vcpkg_from_sourceforge in the baseline's portfile
        text = fetch(f"https://raw.githubusercontent.com/microsoft/vcpkg/{baseline_commit}/ports/{port}/portfile.cmake").decode()
        filename = re.search(r'FILENAME "([^"]+)"', text).group(1).replace("${VERSION}", version)
        url = f"https://sourceforge.net/projects/{port}/files/{filename}/download"  # as vcpkg_from_sourceforge
    return url, re.search(r"SHA512 ([0-9a-f]{128})", text).group(1)


def configure_outputs(checkout):
    """The files configure writes (AC_CONFIG_FILES, AC_CONFIG_HEADERS) per the tag's own
    configure.ac, each from its ".in" template, which is compared with the tag like any source:
    the tarball's copies are replaced when our build runs configure (GraphicsMagick's
    magick/magick_types.h)."""
    for name in ("configure.ac", "configure.in"):
        path = os.path.join(checkout, name)
        if os.path.isfile(path):
            text = read(path)
            break
    else:
        return []
    outputs = []
    for macro in re.finditer(r"AC_CONFIG_(?:FILES|HEADERS)\(\s*\[?([^\])]*)", text):
        for entry in macro.group(1).replace("\\\n", " ").split():
            output = entry.split(":")[0].strip("[]")
            if output and os.path.isfile(os.path.join(checkout, output + ".in")):
                outputs.append(output)
    return outputs


def tree_files(top):
    """Every file under `top` by its relative path, symbolic links included (to a file or to a
    directory, which is not entered): a link is compared as a link, never followed. Left out, a
    source file the tarball turned into a link to code hidden under a documentation name passed."""
    files = {}
    for directory, dirs, names in os.walk(top):
        dirs[:] = [d for d in dirs if d not in (".git", ".hg")]
        for name in names + [d for d in dirs if os.path.islink(os.path.join(directory, d))]:
            path = os.path.join(directory, name)
            files[os.path.relpath(path, top).replace(os.sep, "/")] = path
    return files


def same_file(a, b):
    """Same content, or the same link; a link never equals a file."""
    if os.path.islink(a) or os.path.islink(b):
        return os.path.islink(a) and os.path.islink(b) and os.readlink(a) == os.readlink(b)
    return filecmp.cmp(a, b, shallow=False)


def compare_tarball(port, version, url, sha512, kind, repo, tag, report):
    """True when every file of the tarball is the repository's at the tag (or listed as generated)."""
    with tempfile.TemporaryDirectory() as work:
        archive = os.path.join(work, os.path.basename(url))
        with open(archive, "wb") as f:
            f.write(fetch(url))
        if sha512_of(archive) != sha512:
            report.notes.append(f"**{port} {version}: the archive's SHA-512 is not the pinned one** ({url}).")
            return False
        unpacked = os.path.join(work, "tarball")
        with tarfile.open(archive) as t:
            t.extractall(unpacked, filter="data")
        roots = os.listdir(unpacked)
        tarball = os.path.join(unpacked, roots[0]) if len(roots) == 1 else unpacked
        checkout = os.path.join(work, "repository")
        if kind == "git":
            run("git", "clone", "--quiet", "--depth", "1", "--branch", tag, repo, checkout)
        else:
            run("hg", "clone", "--quiet", "--updaterev", tag, repo, checkout)
        ours, theirs = tree_files(tarball), tree_files(checkout)
        extra = sorted(set(ours) - set(theirs))
        changed = sorted(p for p in set(ours) & set(theirs) if not same_file(ours[p], theirs[p]))
        generated = set(configure_outputs(checkout)) if port in AUTORECONF else set()

        def explained(path):
            if os.path.islink(ours[path]):
                return False  # a link the tag does not have is never documentation nor generated
            return (path in generated or any(fnmatch.fnmatchcase(os.path.basename(path), g) for g in DOCUMENTATION)
                    or (port in AUTORECONF and any(fnmatch.fnmatchcase(path, g) for g in REGENERATED)))
        unexplained = [p for p in extra + changed if not explained(p)]
        if unexplained:
            shown = ", ".join(f"`{p}`" for p in unexplained[:30]) + (" …" if len(unexplained) > 30 else "")
            report.notes.append(f"**{port} {version}: the release tarball differs from {tag} in {len(unexplained)} "
                                f"file(s) not known to be generated**: {shown}. Read them before trusting this "
                                f"release; allow a file in the script only when our build regenerates it.")
            report.rows.append(f"| {port} | {version} | tarball vs `{tag}` | **{len(unexplained)} file(s) differ** |")
            return False
        report.rows.append(f"| {port} | {version} | tarball vs `{tag}` | identical ({len(ours)} files"
                           f"{f', {len(extra) + len(changed)} generated' if extra or changed else ''}) |")
        return True


def sources(baseline_commit, baseline, report):
    ok = True
    checks = [(port, overlay_version(port), kind, repo, template) for port, (kind, repo, template) in TARBALL_PORTS.items()]
    checks.append(("giflib", baseline["giflib"], "git", BASELINE_PORTS["giflib"][0], BASELINE_PORTS["giflib"][1]))
    for port, version, kind, repo, template in checks:
        url, sha512 = tarball_source(port, version, baseline_commit)
        tag = release_tag(repo, template, version)[0] if kind == "git" else template.format(v_=version.replace(".", "_"))
        ok = compare_tarball(port, version, url, sha512, kind, repo, tag, report) and ok
    return ok


def coverage(installed, report):
    """Every port installed under DIR/share is audited."""
    audited = set(BASELINE_PORTS) | set(COMMIT_PORTS) | set(TARBALL_PORTS)
    ports = {name for name in os.listdir(os.path.join(installed, "share"))
             if os.path.isfile(os.path.join(installed, "share", name, "vcpkg.spdx.json"))}
    missing = sorted(p for p in ports - audited if not NOT_SHIPPED.match(p))
    if missing:
        report.notes.append(f"**Not audited**: {', '.join(missing)} — add them to scripts/audit_dependencies.py.")
    return not missing


def spdx_id(text):
    return re.sub(r"[^A-Za-z0-9.-]", "-", text)


def sbom(installed, path, version):
    """An SPDX 2.3 document of one package: ImageViewer, every library it ships from vcpkg (from
    vcpkg's own SPDX files: the port's licence and its upstream sources with their checksums) and
    Qt's modules. Attested with the package in a release (D-67)."""
    qt = read(os.path.join(ROOT, "packaging", "qt-version.txt")).strip()
    packages = [{"SPDXID": "SPDXRef-imageviewer", "name": "ImageViewer", "versionInfo": version,
                 "supplier": "Organization: Cristallumnis", "downloadLocation": "git+https://github.com/njardim/ImageViewer",
                 "licenseConcluded": "Apache-2.0", "licenseDeclared": "Apache-2.0", "copyrightText": "NOASSERTION",
                 "filesAnalyzed": False}]
    relationships = [{"spdxElementId": "SPDXRef-DOCUMENT", "relationshipType": "DESCRIBES",
                      "relatedSpdxElement": "SPDXRef-imageviewer"}]
    share = os.path.join(installed, "share")
    for port in sorted(os.listdir(share)):
        document = os.path.join(share, port, "vcpkg.spdx.json")
        if NOT_SHIPPED.match(port) or not os.path.isfile(document):
            continue
        entries = json.loads(read(document)).get("packages", [])
        recipe = next((e for e in entries if e.get("SPDXID") == "SPDXRef-port"), entries[0] if entries else {})
        ident = f"SPDXRef-{spdx_id(port)}"
        packages.append({"SPDXID": ident, "name": port, "versionInfo": recipe.get("versionInfo", "NOASSERTION"),
                         "downloadLocation": recipe.get("downloadLocation") or "NOASSERTION",
                         "licenseConcluded": recipe.get("licenseConcluded") or "NOASSERTION",
                         "licenseDeclared": recipe.get("licenseDeclared") or "NOASSERTION",
                         "copyrightText": "NOASSERTION", "filesAnalyzed": False})
        if patches := our_patches(port):  # a scanner would otherwise report what they fix
            packages[-1]["comment"] = "Built with ImageViewer's patches: " + "; ".join(
                f"{p['file']} (fixes {', '.join(sorted(p['fixes'])) or 'no listed vulnerability'}; upstream: {p['upstream']})"
                for p in patches)
        relationships.append({"spdxElementId": "SPDXRef-imageviewer", "relationshipType": "CONTAINS",
                              "relatedSpdxElement": ident})
        if port == "imageviewer-svg":  # resvg's crates and Rust's standard library, compiled in (D-90)
            sbom_svg_renderer(os.path.join(share, port), ident, packages, relationships)
        for n, source in enumerate(e for e in entries if str(e.get("SPDXID", "")).startswith("SPDXRef-resource")):
            source_id = f"{ident}-source-{n}"
            packages.append({"SPDXID": source_id, "name": source.get("name", port),
                             "downloadLocation": source.get("downloadLocation") or "NOASSERTION",
                             "checksums": source.get("checksums", []), "licenseConcluded": "NOASSERTION",
                             "licenseDeclared": "NOASSERTION", "copyrightText": "NOASSERTION", "filesAnalyzed": False})
            relationships.append({"spdxElementId": ident, "relationshipType": "GENERATED_FROM",
                                  "relatedSpdxElement": source_id})
    for module in QT_MODULES:
        ident = f"SPDXRef-{module}"
        packages.append({"SPDXID": ident, "name": module, "versionInfo": qt, "supplier": "Organization: The Qt Company",
                         "downloadLocation": f"git+https://code.qt.io/qt/{module}.git@v{qt}",
                         "licenseConcluded": "LGPL-3.0-only", "licenseDeclared": "LGPL-3.0-only OR GPL-2.0-only OR GPL-3.0-only",
                         "copyrightText": "NOASSERTION", "filesAnalyzed": False})
        relationships.append({"spdxElementId": "SPDXRef-imageviewer", "relationshipType": "CONTAINS",
                              "relatedSpdxElement": ident})
    triplet = spdx_id(os.path.basename(os.path.normpath(installed)))
    created = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    document = {"spdxVersion": "SPDX-2.3", "dataLicense": "CC0-1.0", "SPDXID": "SPDXRef-DOCUMENT",
                "name": f"ImageViewer-{version}-{triplet}",
                "documentNamespace": f"https://github.com/njardim/ImageViewer/spdx/{spdx_id(version)}/{triplet}/{uuid.uuid4()}",
                "creationInfo": {"created": created, "creators": ["Tool: scripts/audit_dependencies.py"]},
                "packages": packages, "relationships": relationships}
    with open(path, "w", encoding="utf-8") as f:
        json.dump(document, f, indent=1)
    return len(packages) - 1


def sbom_svg_renderer(share, parent, packages, relationships):
    """The crates built into the SVG renderer (share/imageviewer-svg/crates.tsv: name, version, licence,
    source), with their checksums from Cargo.lock, and the Rust standard library (D-90)."""
    checksums = {(n, v): c for n, v, c in crates()}
    rust = rust_version()
    components = [("rust-std", rust, "MIT OR Apache-2.0", f"git+{RUST}@{rust}", None, None)]
    with open(os.path.join(share, "crates.tsv"), encoding="utf-8") as f:
        for line in f:
            name, version, licence, source = line.rstrip("\n").split("\t")
            if source != "crates.io":
                continue  # resvg's own crates: the port's package
            components.append((name, version, licence or "NOASSERTION", f"https://crates.io/api/v1/crates/{name}/{version}/download",
                               checksums.get((name, version)), f"pkg:cargo/{name}@{version}"))
    for name, version, licence, location, checksum, purl in components:
        ident = f"{parent}-{spdx_id(name)}-{spdx_id(version)}"
        package = {"SPDXID": ident, "name": name, "versionInfo": version, "downloadLocation": location,
                   "licenseConcluded": licence, "licenseDeclared": licence, "copyrightText": "NOASSERTION",
                   "filesAnalyzed": False}
        if checksum:
            package["checksums"] = [{"algorithm": "SHA256", "checksumValue": checksum}]
        if purl:
            package["externalRefs"] = [{"referenceCategory": "PACKAGE-MANAGER", "referenceType": "purl",
                                        "referenceLocator": purl}]
        packages.append(package)
        relationships.append({"spdxElementId": parent, "relationshipType": "CONTAINS", "relatedSpdxElement": ident})


class Report:
    def __init__(self):
        self.rows, self.notes = [], []
        self.stale = []  # cooldown exceptions that no longer apply (scripts/update_dependencies.py removes them)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--vulnerabilities", action="store_true", help="look every shipped library up in OSV")
    parser.add_argument("--sources", action="store_true", help="compare release tarballs with their tags")
    parser.add_argument("--coverage", metavar="DIR", help="vcpkg's installed tree: every port in it is audited")
    parser.add_argument("--cooldown", action="store_true",
                        help=f"every shipped release is {MIN_RELEASE_AGE_DAYS} days old or a recorded exception")
    parser.add_argument("--report", help="write the Markdown report to this file")
    parser.add_argument("--sbom", nargs=3, metavar=("DIR", "FILE", "VERSION"),
                        help="write the SPDX document of the package built from vcpkg's installed tree DIR")
    args = parser.parse_args()
    if args.sbom:
        count = sbom(*args.sbom)
        print(f"{args.sbom[1]}: {count} components")
        return 0
    if not (args.vulnerabilities or args.sources or args.coverage or args.cooldown):
        args.vulnerabilities = args.sources = args.cooldown = True
    out = []
    flags = {"vulnerable": False, "actionable": False, "unassessed": False, "mismatch": False, "unaudited": False,
             "young": False, "failed": False, "lowered": MIN_RELEASE_AGE_DAYS < POLICY_DAYS}
    baseline_commit = json.loads(read(os.path.join(ROOT, "vcpkg.json")))["builtin-baseline"]
    baseline = {}

    def check_vulnerabilities(report):
        flags["vulnerable"], flags["actionable"], flags["unassessed"], unresolved = vulnerabilities(shipped(baseline), report)
        flags["failed"] |= unresolved

    def check_sources(report):
        flags["mismatch"] = not sources(baseline_commit, baseline, report)

    def check_cooldown(report):
        flags["young"] = not cooldown(baseline_commit, baseline, report)

    def check_coverage(report):
        flags["unaudited"] = not coverage(args.coverage, report)
    checks = [
        (args.vulnerabilities, check_vulnerabilities, "Known vulnerabilities (OSV, by commit)",
         ["| Library | Version | Commit | Source | Vulnerabilities |", "|---|---|---|---|---|"]),
        (args.sources, check_sources, "Release tarballs against their tags",
         ["| Library | Version | Compared | Result |", "|---|---|---|---|"]),
        (args.cooldown, check_cooldown, f"Release ages (cooldown: {MIN_RELEASE_AGE_DAYS} days)",
         ["| Library | Version | Released | Age | Status |", "|---|---|---|---|---|"]),
        (args.coverage, check_coverage, "Coverage", []),
    ]
    for wanted, check, title, header in checks:
        if not wanted:
            continue
        report = Report()
        try:
            if not baseline and check is not check_coverage:
                baseline.update(baseline_versions())
            check(report)
        except Exception as error:  # a check that cannot run is never a pass; the others still run
            flags["failed"] = True
            report.notes.append(f"**This check could not run**: {error}")
        out += [f"## {title}", "", *(header + report.rows if report.rows else []), "",
                *[f"- {n}" for n in report.notes or ["nothing to report"]], ""]
    status = 1 if any(flags[k] for k in ("actionable", "unassessed", "mismatch", "unaudited", "young")) else 0
    if flags["failed"]:
        status = 2
    text = "\n".join(out) + "\n"
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text)
    if "GITHUB_OUTPUT" in os.environ:
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as f:
            f.write("".join(f"{k}={'true' if v else 'false'}\n" for k, v in flags.items()))
            f.write(f"cooldown_days={MIN_RELEASE_AGE_DAYS}\n")
    return status


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception:  # an audit that cannot run is never a pass, nor a plain failure (1)
        traceback.print_exc()
        sys.exit(2)
